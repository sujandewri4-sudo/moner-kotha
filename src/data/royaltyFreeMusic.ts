export function searchRoyaltyFreeTracks(query: string): RoyaltyFreeTrack[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return ROYALTY_FREE_CATALOG;

  return ROYALTY_FREE_CATALOG.filter((track) => {
    return (
      track.title.toLowerCase().includes(clean) ||
      track.artist.toLowerCase().includes(clean) ||
      track.genre.toLowerCase().includes(clean) ||
      track.mood.toLowerCase().includes(clean) ||
      track.source.toLowerCase().includes(clean) ||
      track.license.toLowerCase().includes(clean) ||
      track.instruments.some((inst) => inst.toLowerCase().includes(clean))
    );
  });
}
